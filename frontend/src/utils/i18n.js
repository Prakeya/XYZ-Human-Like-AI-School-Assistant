export function dirFor(lang) {
  return RTL_LANGUAGES.has(lang) ? "rtl" : "ltr";
}

// Shared class string for every <thead> in the app. `uppercase` (a CSS
// text-transform) and `tracking-wide` (letter-spacing) are both safe for
// Latin text but break glyph shaping for Indic/Arabic scripts -- combining
// vowel signs and reordering marks (e.g. Tamil "ெ"/"ே", Devanagari matras)
// can render as disconnected boxes once a case-transform or extra
// letter-spacing is applied on top of them. English keeps the emphatic
// uppercase look; every other language just gets the plain translated
// label, which is not affected by this at all.
export function tableHeaderClass(lang) {
  return `bg-paper-alt text-left text-xs font-semibold text-muted ${
    lang === "en" ? "uppercase tracking-wide" : ""
  }`;
}

