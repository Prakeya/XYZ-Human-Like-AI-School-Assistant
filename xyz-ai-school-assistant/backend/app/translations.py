def reason_text(reason_key: Optional[str], language: str = "en", fallback: str = "") -> str:
    """
    Resolve a permissions.py/tools.py `reason_key` to a localized sentence for
    the given language. Falls back to English if the language/key combination
    is missing, and to `fallback` (normally the original English message the
    caller already had) if the key itself is unknown -- so a reason_key that's
    missing from this map degrades gracefully instead of crashing or showing
    a blank reply.
    """
    if not reason_key:
        return fallback
    lang = language if language in FULLY_LOCALIZED else "en"
    entry = REASON_TEXTS.get(reason_key)
    if not entry:
        return fallback
    return entry.get(lang) or entry.get("en") or fallback


def render(template_key: str, language: str = "en", **kwargs) -> str:
    lang = language if language in FULLY_LOCALIZED else "en"
    template_set = TEMPLATES.get(template_key)
    if not template_set:
        return ""
    text = template_set.get(lang) or template_set["en"]
    try:
        return text.format(**kwargs)
    except (KeyError, IndexError):
        return template_set["en"].format(**kwargs)
